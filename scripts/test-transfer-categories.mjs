import assert from 'node:assert/strict';
import {emptyLedger} from '../lib/empty-ledger.ts';
import {makeEntry,totals,report,emptyEffects} from '../lib/ledger.ts';
import {prepareEntry} from '../lib/v2.ts';
import {prepareWrite} from '../lib/write-request.ts';
import {repairTransferCategories,TRANSFER_CATEGORY_REPAIR} from '../lib/transfer-categories.ts';
const base={...emptyLedger('2026-01-01'),openings:{Cash:100000,Alfalah:0}};
const raw={id:'transfer',date:'2026-11-01',month:'2026-11',kind:'transfer',amount:10000,account:'Cash',to:'Alfalah',description:'Transfer to bank',category:'Food',person:'',notes:''};
assert.equal(makeEntry(raw,base).category,'');
assert.equal(prepareEntry(base,{...raw,effects:emptyEffects()}).entries[0].category,'');
const transfer={...makeEntry(raw,base),category:'Food'};
const deleted={...transfer,id:'deleted',deleted:true};
const legacy={...transfer,id:'legacy',kind:'legacy',legacyType:'Internal Transfer'};
const food=makeEntry({...raw,id:'expense',kind:'expense',to:undefined,amount:500},base);
const old={...base,entries:[transfer,deleted,legacy,food],audit:[]};
const original=structuredClone(old),repaired=repairTransferCategories(old);
assert.equal(repaired.count,3);
assert.deepEqual(old,original);
assert.deepEqual(totals(repaired.data),totals(old));
assert.deepEqual(report(repaired.data,'2026-11'),report(old,'2026-11'));
assert.equal(repaired.data.entries[3].category,'Food');
assert.deepEqual(repaired.data.entries[2].original,legacy);
for(let i=0;i<3;i++){const before=old.entries[i],after=repaired.data.entries[i];assert.equal(after.category,'');assert.deepEqual(after.effects,before.effects);assert.equal(after.id,before.id);assert.equal(after.amount,before.amount);assert.equal(after.deleted,before.deleted);}
const committed=await prepareWrite(old,{data:repaired.data,reason:TRANSFER_CATEGORY_REPAIR},async()=>null);
assert.equal(committed.data.audit.length,3);
assert.equal(committed.data.audit[0].before.category,'Food');
assert.equal(committed.data.audit[0].after.category,'');
assert.equal(repairTransferCategories(committed.data).count,0);
assert.deepEqual(repairTransferCategories(committed.data).data,committed.data);
const stale=await prepareWrite(base,{data:{...base,entries:[transfer]},reason:'Saved stale transfer draft'},async()=>null);
assert.equal(stale.data.entries[0].category,'');
console.log('PASS transfer categories: new entries, stale drafts, active/deleted/legacy repair, immutable originals, audit, idempotence, unchanged balances and spending.');
