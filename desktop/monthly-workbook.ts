import * as XLSX from 'xlsx';
import {buildExcel} from '../lib/excel';
import {itemName} from '../lib/ledger-items';
import {accountNames} from '../lib/accounts';
import {report,totals,type Ledger} from '../lib/ledger';

const money='#,##0.00;[Red](#,##0.00);0.00';
const day=86400000;
const note='Generated by BalanceBook. Keep personal notes in a separate file. This report is replaced when its data changes.';
const basis='Spending and income follow Report Month. Closing balances follow Actual Date.';
const serial=(date:string)=>Date.parse(date+'T00:00:00Z')/day+25569;

export function monthlyData(ledger:Ledger,month:string,today:string){
 const [year,number]=month.split('-').map(Number);
 const previous=new Date(Date.UTC(year,number-2,1)).toISOString().slice(0,7);
 const end=new Date(Date.UTC(year,number,0)).toISOString().slice(0,10);
 const cutoff=end<today?end:today;
 const position=cutoff>=month+'-01'&&cutoff>=ledger.baselineDate?totals(ledger,cutoff):null;
 return {
  previous,current:report(ledger,month),prior:report(ledger,previous),cutoff,
  label:month<today.slice(0,7)?'Month end':month===today.slice(0,7)?'Month to date':'Future report month',
  accounts:position?[...new Set([...accountNames(ledger),...Object.keys(position.accounts)])]
   .filter(key=>ledger.accountSettings?.[key]?.status!=='deleted')
   .map(key=>[itemName(ledger,'account',key),(position.accounts[key]||0)/100] as const):[],
  position:position&&[position.receivable,position.payable,position.groupReceivable,position.netWorth].map(value=>value/100),
 };
}

export function buildMonthlyWorkbook(ledger:Ledger,month:string,data:ReturnType<typeof monthlyData>,stamp:string){
 const workbook=buildExcel(ledger,{basis:'report',from:month,to:month});
 const raw=XLSX.utils.sheet_to_json<(string|number)[]>(workbook.Sheets.Transactions,{header:1,defval:''});
 const order=[0,2,4,5,6,7,3,1,12,8,9,10,11,...Array.from({length:16},(_,i)=>i+13)];
 const headers=['Actual Date','Description','Category','Amount (PKR)','Account','Person','Type','Report Month','Notes',...order.slice(9).map(index=>String(raw[0]?.[index]||''))];
 const rows=raw.slice(1).map(row=>order.map((index,i)=>i===0?serial(String(row[index])):i===7?serial(String(row[index])+'-01'):row[index]));
 const tx=XLSX.utils.aoa_to_sheet([[note],[stamp],headers,...rows]);
 tx['!cols']=headers.map((_,i)=>({wch:[16,44,21,17,22,23,22,16,38][i]||22,hidden:i>=9}));
 tx['!autofilter']={ref:'A3:'+XLSX.utils.encode_col(headers.length-1)+(rows.length+3)};
 for(let i=4;i<=rows.length+3;i++){tx['A'+i].z='dd mmm yyyy';tx['H'+i].z='mmm yyyy';tx['D'+i].z=money;}
 workbook.Sheets.Transactions=tx;

 const summaryRows:(string|number)[][]=[
  ['BalanceBook · '+month],[note],[stamp],[basis],[],
  ['Metric (PKR)',month,data.previous,'Change'],
  ...(['income','spend','surplus','refunds'] as const).map((key,i)=>[
   ['Income','Net spending','Surplus','Refunds'][i],data.current[key]/100,data.prior[key]/100,(data.current[key]-data.prior[key])/100
  ]),[],['Category','Net spending (PKR)','Share of net spending'],
 ];
 const categories=Object.entries(data.current.categories).sort((a,b)=>b[1]-a[1]);
 for(const [key,value] of categories)summaryRows.push([itemName(ledger,'category',key),value/100,data.current.spend>0?value/data.current.spend:'—']);
 summaryRows.push([],['Top personal expenses','Spending (PKR)','Actual date']);
 const topHeader=summaryRows.length;
 for(const entry of ledger.entries.filter(e=>!e.deleted&&e.month===month&&e.effects.spend>0)
  .sort((a,b)=>b.effects.spend-a.effects.spend).slice(0,5)){
  summaryRows.push([entry.description,entry.effects.spend/100,serial(entry.date)]);
 }
 const summary=XLSX.utils.aoa_to_sheet(summaryRows);
 summary['!cols']=[{wch:48},{wch:23},{wch:24},{wch:20}];
 summary['!merges']=[1,2,3,4].map(row=>XLSX.utils.decode_range('A'+row+':D'+row));
 for(let i=7;i<=10;i++)for(const col of ['B','C','D'])summary[col+i].z=money;
 for(let i=13;i<13+categories.length;i++){
  summary['B'+i].z=money;
  if(summary['C'+i].t==='n')summary['C'+i].z='0.0%';
 }
 for(let i=topHeader+1;i<=summaryRows.length;i++){summary['B'+i].z=money;summary['C'+i].z='dd mmm yyyy';}
 XLSX.utils.book_append_sheet(workbook,summary,'Summary');
 workbook.SheetNames.unshift(workbook.SheetNames.pop()!);

 const balanceRows:(string|number)[][]=[[note],[stamp],[data.label+' · '+data.cutoff],['Account or balance','PKR']];
 if(data.position){
  balanceRows.push(...data.accounts.map(([name,amount])=>[name,amount]),[],
   ...['People owe you','You owe people','Group reimbursements due','Tracked net worth'].map((name,i)=>[name,data.position![i]]));
 }else balanceRows.push(['No closing snapshot for this period.']);
 const balances=XLSX.utils.aoa_to_sheet(balanceRows);
 balances['!cols']=[{wch:48},{wch:24}];
 balances['!merges']=[1,2,3].map(row=>XLSX.utils.decode_range('A'+row+':B'+row));
 for(let i=5;i<=balanceRows.length;i++)if(balances['B'+i])balances['B'+i].z=money;
 XLSX.utils.book_append_sheet(workbook,balances,'Closing balances');
 const r=data.current;
 XLSX.utils.book_append_sheet(workbook,XLSX.utils.aoa_to_sheet([
  ['Income (PKR)','Net spending (PKR)','Surplus (PKR)','Refunds (PKR)'],
  [r.income/100,r.spend/100,r.surplus/100,r.refunds/100]
 ]),'Month Totals');
 XLSX.utils.sheet_add_aoa(workbook.Sheets.People,[[note],[stamp]],{origin:-1});
 return {workbook,topHeader};
}
